"""The structured, value and area modules generated from the registry are current and keep the v0.7 surface."""

import contextlib
from dataclasses import dataclass
import importlib
import importlib.util
import inspect
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import types
import typing
import unittest
from unittest.mock import patch

import mathforge
from mathforge import registry

REPOSITORY = Path(__file__).resolve().parents[2]
FIXTURES = Path(__file__).resolve().parents[1] / "fixtures" / "v8"
TOOL = REPOSITORY / "tools" / "generate_api.py"
# The tested package's root: src/ in a checkout, site-packages in the distribution harness (no src/).
SRC = Path(mathforge.__file__).resolve().parents[1]
HEADER = ["# Generated by tools/generate_api.py from mathforge.registry. Do not edit.",
          "from __future__ import annotations"]
STALE = "Generated API is stale; run python tools/generate_api.py"
FAMILY = "mathforge._generated_api_test_family"
CHECKER = "mathforge._generated_api_test_checker"
# The v5 record classes each area re-exports, derived from the import block of the v0.7 api_v7.py.
V5_RECORDS = {
    "algebra": {"ComplexAlgebraic", "ComplexRoot"},
    "analysis": {"RealExpr", "RealFunction"},
    "series": {"FunctionLimitValue", "TaylorPolynomial"},
    "integrals": {"RationalPrimitive", "RealExpr", "RealFunction"},
    "linalg": {"LUDecomposition", "LeastSquaresResult"},
    "stats": {"FiniteDistribution"},
    "ntheory": {"CRTResult", "IntegerFactorization"},
}


def load_tool():
    spec = importlib.util.spec_from_file_location("generate_api", TOOL)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def published(name):
    return json.loads((FIXTURES / name).read_text(encoding="utf-8"))


def demo_spec(annotation="int", returns="DemoBox"):
    """A throwaway v6 operation of the discrete area."""
    return registry.OperationSpec("demo_triple", "discrete", (registry.Argument("n", annotation, None, "int"),),
                                  returns, "Triple an exact integer.", "test only", version=6, mcp=False)


@dataclass(frozen=True)
class DemoBox:
    __module__ = FAMILY  # v6 records are defined in their family module.
    n: int


class GeneratedApiTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tool = load_tool()

    def install_family(self, *specs, records=None):
        """Register a throwaway v6 family for the rest of this test; the registry cache starts cold."""
        family, checker = types.ModuleType(FAMILY), types.ModuleType(CHECKER)
        family.SPECS, family.TYPES, family.CHECKER = specs, dict(records or {}), CHECKER
        for module in (family, checker):
            sys.modules[module.__name__] = module
            self.addCleanup(sys.modules.pop, module.__name__, None)
        patcher = patch.object(registry, "V6_FAMILIES", (FAMILY,))
        patcher.start()
        self.addCleanup(patcher.stop)
        self.addCleanup(registry._clear_caches)
        registry._clear_caches()

    def rendered(self, relative):
        return self.tool.render_files(SRC)[SRC / "mathforge" / relative]

    def test_generated_files_are_current(self):
        files = self.tool.render_files(SRC)
        package = SRC / "mathforge"
        expected = {package / "_generated" / name for name in ("__init__.py", "structured.py", "values.py")}
        self.assertEqual(set(files), expected | {package / (area + ".py") for area in registry.AREAS})
        for path, text in files.items():
            with self.subTest(path=path.relative_to(SRC).as_posix()):
                self.assertEqual(text.splitlines()[:2], HEADER)
                self.assertTrue(path.is_file())
                self.assertEqual(path.read_text(encoding="utf-8"), text)

    def test_v07_signatures_preserved(self):
        from mathforge import api_v7, operations, values_v7
        signatures = published("api_v7_signatures.json")
        for module, key in ((api_v7, "api_v7"), (values_v7, "values_v7")):
            self.assertEqual(sorted(module.__all__), sorted(signatures[key]))
            for name, text in signatures[key].items():
                with self.subTest(module=key, name=name):
                    function = getattr(module, name)
                    self.assertEqual(str(inspect.signature(function)), text)
                    self.assertIn("return", typing.get_type_hints(function))  # Every annotation name is imported.
        self.assertEqual(values_v7.__all__, api_v7.__all__)
        # mathforge.operations still exposes all 100 v0.7 operation functions with their signatures.
        for name, text in signatures["operations"].items():
            with self.subTest(module="operations", name=name):
                self.assertEqual(str(inspect.signature(getattr(operations, name))), text)

    def test_area_module_parity(self):
        ntheory = importlib.import_module("mathforge.ntheory")
        values_v7 = importlib.import_module("mathforge.values_v7")
        self.assertEqual(ntheory.integer_gcd(84, 30), 6)
        self.assertIs(ntheory.integer_gcd, values_v7.integer_gcd)
        self.assertIs(ntheory.integer_gcd, mathforge.integer_gcd)
        self.assertIs(mathforge.operations.integer_gcd, importlib.import_module("mathforge.api_v7").integer_gcd)
        self.assertIn("CRTResult", ntheory.__all__)
        self.assertEqual(importlib.import_module("mathforge.logic").__all__, [])
        generated = importlib.import_module("mathforge._generated.values")
        structured = importlib.import_module("mathforge._generated.structured")
        api_v7 = importlib.import_module("mathforge.api_v7")
        for name in api_v7.__all__:  # The v0.7 modules only re-export the generated wrappers.
            with self.subTest(name=name):
                self.assertIs(getattr(api_v7, name), getattr(structured, name))
                self.assertIs(getattr(values_v7, name), getattr(generated, name))
        for area in registry.AREAS:
            module = importlib.import_module("mathforge." + area)
            with self.subTest(area=area):
                exported = set(module.__all__)
                self.assertEqual(len(exported), len(module.__all__))
                functions = {spec.public_name for spec in registry.area_operations(area)}
                self.assertLessEqual(functions, exported)
                for name in functions:
                    self.assertIs(getattr(module, name), getattr(generated, name))
                for name in exported - functions:
                    self.assertTrue(inspect.isclass(getattr(module, name)), name)
                self.assertLessEqual(V5_RECORDS.get(area, set()), exported - functions)
                for name in V5_RECORDS.get(area, ()):
                    self.assertIs(getattr(module, name), getattr(mathforge, name))

    def test_rendering_is_deterministic(self):
        expected = {path.relative_to(SRC).as_posix(): text for path, text in self.tool.render_files(SRC).items()}
        self.assertFalse([name for name, text in expected.items() if "\r" in text])
        probe = ("import importlib.util, json, sys; from pathlib import Path; root = Path(sys.argv[2]); "
                 "sys.path.insert(0, str(root)); "
                 "spec = importlib.util.spec_from_file_location('generate_api', sys.argv[1]); "
                 "tool = importlib.util.module_from_spec(spec); spec.loader.exec_module(tool); "
                 "print(json.dumps({p.relative_to(root).as_posix(): t for p, t in tool.render_files(root).items()}))")
        for seed in ("0", "2718281"):
            with self.subTest(seed=seed):
                # Not -I: isolated mode would ignore PYTHONHASHSEED; the probe puts the package first itself.
                output = subprocess.run([sys.executable, "-c", probe, str(TOOL), str(SRC)], capture_output=True,
                                        text=True, env=dict(os.environ, PYTHONHASHSEED=seed))
                self.assertEqual(output.returncode, 0, output.stderr)
                self.assertEqual(json.loads(output.stdout), expected)

    def test_unknown_annotation_names_are_rejected(self):
        self.install_family(demo_spec(annotation="Mystery"), records={"demo_box": DemoBox})
        with self.assertRaisesRegex(ValueError, "Mystery"):
            self.tool.render_files(SRC)

    def test_v6_operations_use_the_v6_runner(self):
        self.assertNotIn("operations_v6", self.rendered("_generated/structured.py"))  # No v6 operation exists yet.
        self.install_family(demo_spec(), records={"demo_box": DemoBox})
        structured = self.rendered("_generated/structured.py")
        self.assertIn("from ..operations_v6 import run as run_v6\n", structured)
        self.assertIn("from .._generated_api_test_family import DemoBox\n", structured)
        self.assertIn("def demo_triple(n: int, *, limits: ComputationLimits | None = None) -> Result[DemoBox]:\n"
                      '    return run_v6("demo_triple", dict(n=n), limits=limits)\n', structured)
        self.assertIn('    return run("integer_gcd", dict(a=a, b=b), limits=limits)\n', structured)
        self.assertIn("def demo_triple(n: int, *, limits: ComputationLimits | None = None) -> DemoBox:\n"
                      "    return structured.demo_triple(n, limits=limits).unwrap()\n",
                      self.rendered("_generated/values.py"))
        discrete = self.rendered("discrete.py")
        self.assertIn("from ._generated_api_test_family import DemoBox\n", discrete)
        self.assertIn('    "DemoBox",\n', discrete)
        self.assertIn('    "demo_triple",\n', discrete)

    def test_check_mode(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            files = self.tool.render_files(root)
            for path, text in files.items():
                path.parent.mkdir(parents=True, exist_ok=True)
                # A checkout with core.autocrlf=true holds CRLF copies; they still count as current.
                path.write_text(text, encoding="utf-8", newline="\r\n" if path.name == "values.py" else "\n")
            stale = root / "mathforge" / "ntheory.py"
            with patch.object(self.tool, "SRC", root):
                with contextlib.redirect_stdout(io.StringIO()) as output:
                    self.tool.main(["--check"])
                self.assertEqual(output.getvalue(), "Generated API matches the registry.\n")
                stale.write_text(files[stale].replace("integer_gcd", "integer_gcf"), encoding="utf-8", newline="\n")
                with self.assertRaises(SystemExit) as caught:
                    self.tool.main(["--check"])
                self.assertEqual(str(caught.exception.code).splitlines(), [STALE, "  mathforge/ntheory.py"])
                with contextlib.redirect_stdout(io.StringIO()):
                    self.tool.main([])
                self.assertEqual(stale.read_bytes(), files[stale].encode("utf-8"))
                with contextlib.redirect_stdout(io.StringIO()) as output:
                    self.tool.main(["--check"])
                self.assertEqual(output.getvalue(), "Generated API matches the registry.\n")


if __name__ == "__main__":
    unittest.main()
