"""Generate the structured, value and area API modules from mathforge.registry, or check them.

The registry is the single source of truth for operations. This tool writes static modules from it,
so that type checkers see real signatures:

- mathforge/_generated/structured.py: one Result-returning wrapper per operation. It calls the run
  function of the operation's result format version: operations_v5.run or operations_v6.run.
- mathforge/_generated/values.py: the same signatures, returning the unwrapped value.
- mathforge/<area>.py for each of the 18 registry.AREAS: the value functions of the area's operations
  and the record classes of its families.

``import mathforge`` loads both _generated modules, so the annotation names that only version-6
operations use are imported there under TYPE_CHECKING and their family modules stay unloaded; the
area modules, which load lazily, import their record classes at runtime.

mathforge.api_v7 and mathforge.values_v7 re-export the v0.7 names from mathforge._generated.

Run ``python tools/generate_api.py`` after changing the registry; it rewrites only stale files.
``--check`` writes nothing and fails when a generated file is missing or stale. When importing
mathforge fails, as a broken or conflicted generated file makes it, the tool prints how to restore
the generated files and exits with status 1. The output depends only on the registry: it is the
same on every supported Python version and hash seed, with LF line endings. Saved files are
compared as text, so a checkout with CRLF line endings still counts as current.
"""

from __future__ import annotations

import argparse
import ast
import builtins
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
import sys
import textwrap


REPOSITORY = Path(__file__).resolve().parents[1]
SRC = REPOSITORY / "src"
sys.path.insert(0, str(SRC))
RECOVERY = """Importing mathforge, which tools/generate_api.py needs to read the registry, failed:
  {error}
A broken or conflicted generated file stops that import. Restore the generated files, then regenerate:
  git checkout -- src/mathforge/_generated src/mathforge/<area>.py
  python tools/generate_api.py
Name each area module (<area>.py) that is broken or conflicted."""

try:
    from mathforge import registry  # noqa: E402  (needs the path above when mathforge is not installed)
    from mathforge.registry import OperationSpec  # noqa: E402
except Exception as error:  # A SyntaxError or NameError in a generated module, as much as an ImportError.
    sys.exit(RECOVERY.format(error=f"{type(error).__name__}: {error}"))

HEADER = "# Generated by tools/generate_api.py from mathforge.registry. Do not edit."
STALE = "Generated API is stale; run python tools/generate_api.py"
CURRENT = "Generated API matches the registry."
PACKAGE = "mathforge"
GENERATED = PACKAGE + "._generated"
IMPORT_LINE_LENGTH = 100  # Longer from-imports are wrapped, one name per line.
LIMITS = "limits: ComputationLimits | None = None"
# Result format version -> (module, imported name, local name) of the run function structured.py calls.
RUNNERS = {5: ("mathforge.operations_v5", "run", "run"),
           6: ("mathforge.operations_v6", "run as run_v6", "run_v6")}

# Annotation name -> the module of its import line, copied in order from the import block of the
# v0.7 api_v7.py. Builtins need no entry; record classes of registered families are found on their own.
NAME_SOURCES: dict[str, str] = {
    "Result": "mathforge.contracts",
    "ComputationLimits": "mathforge.limits",
    "Rational": "mathforge.model",
    "Symbol": "mathforge.model",
    "Expression": "mathforge.model",
    "Matrix": "mathforge.matrices",
    "CRTResult": "mathforge.number_theory",
    "IntegerFactorization": "mathforge.number_theory",
    "ComplexAlgebraic": "mathforge.complex_numbers",
    "ComplexRoot": "mathforge.complex_numbers",
    "FiniteDistribution": "mathforge.probability",
    "LUDecomposition": "mathforge.linear_extensions",
    "LeastSquaresResult": "mathforge.linear_extensions",
    "RealExpr": "mathforge.functions",
    "RealFunction": "mathforge.functions",
    "RealAlgebraicRoot": "mathforge.algebraic",
    "TaylorPolynomial": "mathforge.function_calculus",
    "FunctionLimitValue": "mathforge.function_calculus",
    "RationalPrimitive": "mathforge.rational_integration",
}

# The v5 record classes each area module exports, derived from the import block of the v0.7 api_v7.py:
# a class imported there from a v5 family module appears in every area with an operation whose signature
# names it. An area also exports the record classes (TYPES) of the v6 families that have operations in it.
V5_AREA_RECORDS: dict[str, tuple[str, ...]] = {
    "algebra": ("ComplexAlgebraic", "ComplexRoot"),
    "analysis": ("RealExpr", "RealFunction"),
    "series": ("TaylorPolynomial", "FunctionLimitValue"),
    "integrals": ("RealExpr", "RealFunction", "RationalPrimitive"),
    "linalg": ("LUDecomposition", "LeastSquaresResult"),
    "stats": ("FiniteDistribution",),
    "ntheory": ("CRTResult", "IntegerFactorization"),
}


def _annotation_names(text: str) -> list[str]:
    """The names that an annotation's source text refers to, sorted (a dotted reference gives its first name)."""
    try:
        tree = ast.parse(text, mode="eval")
    except SyntaxError:
        raise ValueError(f"Annotation is not a Python expression: {text!r}") from None
    return sorted({node.id for node in ast.walk(tree) if isinstance(node, ast.Name)})


class _Names:
    """Resolves annotation names to their modules: NAME_SOURCES, builtins, then registered record classes."""

    def __init__(self) -> None:
        self.sources = dict(NAME_SOURCES)
        found: dict[str, set[str]] = {}
        for cls in registry.all_record_types():
            if cls.__name__ not in self.sources and not hasattr(builtins, cls.__name__):
                found.setdefault(cls.__name__, set()).add(cls.__module__)
        self.ambiguous = {name: sorted(modules) for name, modules in found.items() if len(modules) > 1}
        self.sources.update({name: min(modules) for name, modules in found.items() if len(modules) == 1})

    def of(self, spec: OperationSpec) -> set[str]:
        """The names a wrapper of spec must import for its annotations."""
        texts = [argument.annotation for argument in spec.arguments if argument.annotation]
        names = set()
        for name in (name for text in texts + [spec.returns] for name in _annotation_names(text)):
            if name in self.sources:
                names.add(name)
            elif name in self.ambiguous:
                raise ValueError(f"Operation {spec.name!r}: annotation name {name!r} is ambiguous between "
                                 f"{', '.join(self.ambiguous[name])}; add it to NAME_SOURCES")
            elif not hasattr(builtins, name):
                raise ValueError(f"Operation {spec.name!r}: unknown annotation name {name!r}; "
                                 "add it to NAME_SOURCES in tools/generate_api.py")
        return names


def _relative(module: str, package: str) -> str:
    """How a module of package imports module: relatively inside mathforge, absolutely outside it."""
    if module != PACKAGE and not module.startswith(PACKAGE + "."):
        return module
    return "." * (package.count(".") + 1) + module[len(PACKAGE) + 1:]


def _from_import(module: str, names: Sequence[str]) -> str:
    line = f"from {module} import {', '.join(names)}"
    if len(line) <= IMPORT_LINE_LENGTH:
        return line
    return "\n".join([f"from {module} import (", *(f"    {name}," for name in names), ")"])


def _import_lines(sources: Mapping[str, str], names: Iterable[str], package: str) -> list[str]:
    """From-import lines grouped by module, in NAME_SOURCES order; other names follow sorted by module and name."""
    rank = {name: index for index, name in enumerate(NAME_SOURCES)}
    grouped: dict[str, list[str]] = {}
    for name in sorted(set(names), key=lambda name: (rank.get(name, len(rank)), sources[name], name)):
        grouped.setdefault(sources[name], []).append(name)
    return [_from_import(_relative(module, package), members) for module, members in grouped.items()]


def _all(names: Sequence[str]) -> str:
    if not names:
        return "__all__: list[str] = []"
    return "\n".join(["__all__ = [", *(f'    "{name}",' for name in names), "]"])


def _module(blocks: Sequence[str], functions: Sequence[str] = ()) -> str:
    """The header and the nonempty top blocks one blank line apart, then the functions two blank lines apart."""
    text = "\n\n".join([HEADER + "\nfrom __future__ import annotations", *(block for block in blocks if block)])
    return text + "\n" + "".join("\n\n" + function for function in functions)


def _check_unique(label: str, names: Iterable[str]) -> None:
    seen: set[str] = set()
    for name in names:
        if name in seen:
            raise ValueError(f"{label} would bind {name!r} twice")
        seen.add(name)


def _check_spec(spec: OperationSpec) -> None:
    """The registry build has checked the names and defaults of every spec; the run function is the generator's."""
    if spec.version not in RUNNERS:
        raise ValueError(f"Operation {spec.name!r}: no run function for result format version {spec.version}")


def _check_wrapper_names(label: str, text: str) -> None:
    """Fail when a generated wrapper uses a name, besides its own arguments, that registry.WRAPPER_NAMES lacks.

    The registry build keeps arguments and public names out of WRAPPER_NAMES, so that no operation can shadow a
    name the wrappers rely on; a wrapper that starts using another name needs it reserved there first.
    """
    for function in ast.parse(text).body:
        if isinstance(function, ast.FunctionDef):
            own = {argument.arg for argument in function.args.args}
            used = {argument.arg for argument in function.args.kwonlyargs}
            used.update(node.id for statement in function.body for node in ast.walk(statement)
                        if isinstance(node, ast.Name))
            stray = sorted(used - own - set(registry.WRAPPER_NAMES))
            if stray:
                raise ValueError(f"Generated {label}: {function.name} uses {', '.join(stray)}, which "
                                 "registry.WRAPPER_NAMES must reserve")


def _parameters(spec: OperationSpec) -> str:
    parameters = []
    for argument in spec.arguments:
        text = argument.name + (": " + argument.annotation if argument.annotation else "")
        if argument.default is not None:
            text += (" = " if argument.annotation else "=") + argument.default
        parameters.append(text)
    return ", ".join([*parameters, "*", LIMITS])


def _import_blocks(names: _Names, specs: Sequence[OperationSpec], always: Iterable[str],
                   tail: Sequence[str]) -> tuple[list[str], list[str]]:
    """The import blocks of a wrapper module, and the names they bind.

    Names that a version-5 (v0.7) wrapper uses are runtime imports, as in v0.7, so typing.get_type_hints() still
    resolves those wrappers. Names that only later versions use are imported under TYPE_CHECKING: their record
    classes live in family modules, which a runtime import would load during ``import mathforge``.
    """
    runtime = set(always)
    checking: set[str] = set()
    for spec in specs:
        (runtime if spec.version == 5 else checking).update(names.of(spec))
    checking -= runtime
    lines = [*_import_lines(names.sources, runtime, GENERATED), *tail]
    if not checking:
        return ["\n".join(lines)], sorted(runtime)
    deferred = textwrap.indent("\n".join(_import_lines(names.sources, checking, GENERATED)), "    ")
    return (["\n".join(["from typing import TYPE_CHECKING", *lines]), "if TYPE_CHECKING:\n" + deferred],
            [*sorted(runtime), *sorted(checking), "TYPE_CHECKING"])


def _structured(specs: Sequence[OperationSpec], names: _Names) -> str:
    versions = sorted({spec.version for spec in specs})
    runners = [_from_import(_relative(RUNNERS[version][0], GENERATED), [RUNNERS[version][1]]) for version in versions]
    blocks, bound = _import_blocks(names, specs, ("Result", "ComputationLimits"), runners)
    _check_unique("structured.py", [*bound, *(RUNNERS[version][2] for version in versions),
                                    *(spec.public_name for spec in specs)])
    functions = []
    for spec in specs:
        arguments = ", ".join(f"{argument.name}={argument.name}" for argument in spec.arguments)
        functions.append(f"def {spec.public_name}({_parameters(spec)}) -> Result[{spec.returns}]:\n"
                         f'    return {RUNNERS[spec.version][2]}("{spec.name}", dict({arguments}), limits=limits)\n')
    return _module([_all([spec.public_name for spec in specs]), *blocks], functions)


def _values(specs: Sequence[OperationSpec], names: _Names) -> str:
    blocks, bound = _import_blocks(names, specs, ("ComputationLimits",), ["from . import structured"])
    _check_unique("values.py", [*bound, "structured", *(spec.public_name for spec in specs)])
    functions = []
    for spec in specs:
        arguments = ", ".join([*(argument.name for argument in spec.arguments), "limits=limits"])
        functions.append(f"def {spec.public_name}({_parameters(spec)}) -> {spec.returns}:\n"
                         f"    return structured.{spec.public_name}({arguments}).unwrap()\n")
    return _module([_all([spec.public_name for spec in specs]), *blocks], functions)


def _area(area: str, specs: Sequence[OperationSpec]) -> str:
    records: dict[str, str] = {}  # Record class name -> its module.

    def add(name: str, module: str) -> None:
        if records.setdefault(name, module) != module:
            raise ValueError(f"Area {area!r} would export two record classes named {name!r}")

    for name in V5_AREA_RECORDS.get(area, ()):
        if name not in NAME_SOURCES:
            raise ValueError(f"Area {area!r}: record class {name!r} is missing from NAME_SOURCES")
        add(name, NAME_SOURCES[name])
    for spec in specs:
        if spec.version == 6:
            for cls in getattr(registry.family(spec.name), "TYPES", {}).values():
                add(cls.__name__, cls.__module__)
    functions = [spec.public_name for spec in specs]
    _check_unique(f"{area}.py", [*functions, *records])
    imports = [_from_import(_relative(GENERATED + ".values", PACKAGE), functions)] if functions else []
    imports += _import_lines(records, records, PACKAGE)
    return _module([_all(sorted([*functions, *records])), "\n".join(imports)])


def _package_init() -> str:
    return _module(["# structured: a Result-returning wrapper for every registry operation. values: the same\n"
                    "# signatures, returning the unwrapped value. mathforge.api_v7, mathforge.values_v7 and the\n"
                    "# area modules re-export them."])


def render_files(src_root: Path) -> dict[Path, str]:
    """Map each generated file below src_root (the directory holding the mathforge package) to its exact text."""
    specs = tuple(registry.specs().values())
    for spec in specs:
        _check_spec(spec)
    names = _Names()
    package = src_root / PACKAGE
    files = {
        package / "_generated" / "__init__.py": _package_init(),
        package / "_generated" / "structured.py": _structured(specs, names),
        package / "_generated" / "values.py": _values(specs, names),
    }
    for area in registry.AREAS:
        files[package / f"{area}.py"] = _area(area, registry.area_operations(area))
    for path, text in files.items():
        label = path.relative_to(src_root).as_posix()
        try:
            compile(text, label, "exec", dont_inherit=True)
        except SyntaxError as error:
            raise ValueError(f"Generated {label} is not valid Python: {error}") from None
        if path.parent.name == "_generated":
            _check_wrapper_names(label, text)
    return files


def _current(path: Path, text: str) -> bool:
    try:
        return path.read_text(encoding="utf-8") == text
    except (OSError, UnicodeDecodeError):
        return False


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="Write nothing; fail if a generated file is missing or stale")
    arguments = parser.parse_args(argv)
    files = render_files(SRC)
    stale = [path for path, text in files.items() if not _current(path, text)]
    if arguments.check:
        if stale:
            raise SystemExit("\n".join([STALE, *("  " + path.relative_to(SRC).as_posix() for path in stale)]))
        print(CURRENT)
        return
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding="utf-8", newline="\n")
        print(path.relative_to(SRC).as_posix())
    if not stale:
        print(CURRENT)


if __name__ == "__main__":
    main()
